void fb_draw_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (!g_fb.active || x >= g_fb.width || y >= g_fb.height) return;

    uint8_t *fb_ptr = (uint8_t *)g_fb.virt_addr;
    uint32_t offset = (y * g_fb.pitch) + (x * (g_fb.bpp / 8));

    if (g_fb.bpp == 32) {
        *(uint32_t *)(fb_ptr + offset) = color;
    } else if (g_fb.bpp == 24) {
        fb_ptr[offset + 0] = (uint8_t)(color & 0xFF);         // Blue
        fb_ptr[offset + 1] = (uint8_t)((color >> 8) & 0xFF);  // Green
        fb_ptr[offset + 2] = (uint8_t)((color >> 16) & 0xFF); // Red
    }
}

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    if (!g_fb.active) return;
    if (x >= g_fb.width || y >= g_fb.height) return;

    if (x + w > g_fb.width) w = g_fb.width - x;
    if (y + h > g_fb.height) h = g_fb.height - y;

    for (uint32_t row = 0; row < h; row++) {
        uint32_t cur_y = y + row;
        for (uint32_t col = 0; col < w; col++) {
            fb_draw_pixel(x + col, cur_y, color);
        }
    }
}

void fb_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    if (!g_fb.active) return;
    uint8_t ch = (uint8_t)c;
    if (ch >= 128) ch = '?';

    for (uint32_t row = 0; row < FONT_HEIGHT; row++) {
        uint8_t bits = g_fb_font[ch][row];
        for (uint32_t col = 0; col < FONT_WIDTH; col++) {
            if (bits & (0x80 >> col)) {
                fb_draw_pixel(x + col, y + row, fg);
            } else if (bg != COLOR_BG) {
                fb_draw_pixel(x + col, y + row, bg);
            }
        }
    }
}

void fb_draw_string(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg) {
    if (!str) return;
    uint32_t cur_x = x;
    while (*str) {
        fb_draw_char(cur_x, y, *str, fg, bg);
        cur_x += FONT_WIDTH;
        str++;
    }
}

