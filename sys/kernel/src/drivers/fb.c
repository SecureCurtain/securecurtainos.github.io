int fb_init(uint64_t phys_addr, uint32_t width, uint32_t height, uint32_t pitch, uint8_t bpp) {
    if (!phys_addr || width == 0 || height == 0 || bpp < 24) {
        return -1;
    }

    g_fb.phys_addr = phys_addr;
    g_fb.width = width;
    g_fb.height = height;
    g_fb.pitch = pitch;
    g_fb.bpp = bpp;
    g_fb.virt_addr = FRAMEBUFFER_VIRT_BASE;

    /* Map framebuffer into kernel virtual address space */
    size_t total_fb_bytes = (size_t)height * pitch;
    size_t num_pages = (total_fb_bytes + PAGE_SIZE - 1) / PAGE_SIZE;

    for (size_t i = 0; i < num_pages; i++) {
        uintptr_t v_addr = g_fb.virt_addr + (i * PAGE_SIZE);
        uintptr_t p_addr = g_fb.phys_addr + (i * PAGE_SIZE);
        vmm_map_page(v_addr, p_addr, VMM_PAGE_PRESENT | VMM_PAGE_WRITABLE | VMM_PAGE_NOCACHE);
    }

    g_fb.active = true;

    /* Calculate console capacity */
    uint32_t usable_w = width - (CONSOLE_MARGIN_LEFT + CONSOLE_MARGIN_RIGHT);
    uint32_t usable_h = height - (CONSOLE_MARGIN_TOP + CONSOLE_MARGIN_BOTTOM);
    g_con_cols = usable_w / FONT_WIDTH;
    g_con_rows = usable_h / FONT_HEIGHT;
    g_con_x = 0;
    g_con_y = 0;

    /* Clear screen to deep midnight background */
    fb_fill_rect(0, 0, width, height, COLOR_BG);

    /* Draw UI headers, system branding, and console frame */
    fb_draw_decorations();

    return 0;
}

