/* Terminal State */
#define CONSOLE_MARGIN_TOP    32
#define CONSOLE_MARGIN_BOTTOM 32
#define CONSOLE_MARGIN_LEFT   16
#define CONSOLE_MARGIN_RIGHT  16
#define FONT_WIDTH  8
#define FONT_HEIGHT 16

