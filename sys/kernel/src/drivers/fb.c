static void fb_console_scroll(void) {
    if (!g_fb.active || g_con_rows == 0) return;

    uint32_t src_y_start = CONSOLE_MARGIN_TOP + FONT_HEIGHT;
    uint32_t dst_y_start = CONSOLE_MARGIN_TOP;
    uint32_t copy_height = (g_con_rows - 1) * FONT_HEIGHT;
    uint32_t width_bytes = g_fb.width * (g_fb.bpp / 8);

    uint8_t *fb = (uint8_t *)g_fb.virt_addr;

    /* Scroll pixel rows up by one font height */
    for (uint32_t y = 0; y < copy_height; y++) {
        uint8_t *dst = fb + ((dst_y_start + y) * g_fb.pitch);
        uint8_t *src = fb + ((src_y_start + y) * g_fb.pitch);
        memcpy(dst, src, width_bytes);
    }

    /* Clear bottom character row */
    uint32_t clear_y = CONSOLE_MARGIN_TOP + copy_height;
    fb_fill_rect(0, clear_y, g_fb.width, FONT_HEIGHT, COLOR_BG);

    g_con_y = g_con_rows - 1;
}

void fb_console_putc(char c) {
    if (!g_fb.active) return;

    if (c == '\r') {
        g_con_x = 0;
        return;
    }

    if (c == '\n') {
        g_con_x = 0;
        g_con_y++;
        g_line_prefix_len = 0;
        g_current_color = COLOR_TEXT_DEFAULT;
        if (g_con_y >= g_con_rows) {
            fb_console_scroll();
        }
        return;
    }

    if (c == '\t') {
        uint32_t spaces = 4 - (g_con_x % 4);
        for (uint32_t s = 0; s < spaces; s++) {
            fb_console_putc(' ');
        }
        return;
    }

    if (c == '\b') {
        if (g_con_x > 0) {
            g_con_x--;
            uint32_t px = CONSOLE_MARGIN_LEFT + (g_con_x * FONT_WIDTH);
            uint32_t py = CONSOLE_MARGIN_TOP + (g_con_y * FONT_HEIGHT);
            fb_fill_rect(px, py, FONT_WIDTH, FONT_HEIGHT, COLOR_BG);
        }
        return;
    }

    /* Buffer the beginning of the line to detect status tag prefixes */
    if (g_con_x < 12 && g_line_prefix_len < sizeof(g_line_prefix_buf) - 1) {
        g_line_prefix_buf[g_line_prefix_len++] = c;
        g_line_prefix_buf[g_line_prefix_len] = '\0';

        if (g_line_prefix_len >= 3) {
            if (g_line_prefix_buf[0] == '[' && g_line_prefix_buf[1] == '+' && g_line_prefix_buf[2] == ']') {
                g_current_color = COLOR_TAG_SUCCESS;
            } else if (g_line_prefix_buf[0] == '[' && g_line_prefix_buf[1] == '*' && g_line_prefix_buf[2] == ']') {
                g_current_color = COLOR_TAG_INFO;
            } else if (g_line_prefix_buf[0] == '[' && g_line_prefix_buf[1] == '!' && g_line_prefix_buf[2] == ']') {
                g_current_color = COLOR_TAG_WARN;
            } else if (g_line_prefix_buf[0] == '[' && g_line_prefix_buf[1] == '-' && g_line_prefix_buf[2] == ']') {
                g_current_color = COLOR_TAG_ERROR;
            } else if (g_line_prefix_buf[0] == '[' && (g_line_prefix_buf[1] == 'U' || g_line_prefix_buf[1] == 'I')) {
                g_current_color = COLOR_TAG_USERLAND;
            }
        }
    }

    /* Render character */
    uint32_t px = CONSOLE_MARGIN_LEFT + (g_con_x * FONT_WIDTH);
    uint32_t py = CONSOLE_MARGIN_TOP + (g_con_y * FONT_HEIGHT);

    fb_draw_char(px, py, c, g_current_color, COLOR_BG);

    g_con_x++;
    if (g_con_x >= g_con_cols) {
        g_con_x = 0;
        g_con_y++;
        g_line_prefix_len = 0;
        g_current_color = COLOR_TEXT_DEFAULT;
        if (g_con_y >= g_con_rows) {
            fb_console_scroll();
        }
    }
}

void fb_console_puts(const char *str) {
    if (!str) return;
    while (*str) {
        fb_console_putc(*str);
        str++;
    }
}
