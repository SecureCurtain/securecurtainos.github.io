void gfx_draw_filled_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    uint32_t scaled_x = sys_scale_coordinate_value(x);
    uint32_t scaled_y = sys_scale_coordinate_value(y);
    uint32_t scaled_w = sys_scale_coordinate_value(w);
    uint32_t scaled_h = sys_scale_coordinate_value(h);

    uint32_t active_aperture = 600; 
    uint32_t my_pid = 100;

    for (uint32_t curr_y = 0; curr_y < scaled_h; curr_y++) {
        for (uint32_t curr_x = 0; curr_x < scaled_w; curr_x++) {
            sys_gop_blit_pixel_stream(active_aperture, my_pid, scaled_x + curr_x, scaled_y + curr_y, color);
        }
    }
}

void gfx_draw_string(uint32_t x, uint32_t y, const char* text, uint32_t color) {
    if (!text) return;
    uint32_t cursor_x = x;

    while (*text) {
        uint8_t ascii_idx = (uint8_t)*text;
        if (ascii_idx >= 128) ascii_idx = '?';
        
        // Loop sequentially over the 16 vertical pixel scanlines of the character bitmap
        for (uint32_t row = 0; row < 16; row++) {
            uint8_t bits = g_kfont_bitmap[ascii_idx][row];
            
            // Sweep horizontally bit-by-bit across the 8 columns of the character row
            for (uint32_t col = 0; col < 8; col++) {
                if (bits & (0x80 >> col)) {
                    uint32_t s_x = sys_scale_coordinate_value(cursor_x + col);
                    uint32_t s_y = sys_scale_coordinate_value(y + row);
                    sys_gop_blit_pixel_stream(600, 100, s_x, s_y, color);
                }
            }
        }
        cursor_x += 10; // Slide text column advance space
        text++;
    }
}

